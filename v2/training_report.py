"""Training evidence: one report + one figure covering every trained model.

Reads the per-epoch training records (results/info_*.json), the saved checkpoints (models/*.pt, which also store the
epoch history), the training logs (results/logs/*.log) and the XGBoost metadata, cross-checks them against each other,
and writes:
  results/training_report.md
  figures/fig8_training_all_seeds.png
"""
import os, re, json, glob, hashlib, sys
import numpy as np, torch
HERE = os.path.dirname(os.path.abspath(__file__)); RES = os.path.join(HERE, "results"); MOD = os.path.join(HERE, "models")
LOGS = os.path.join(RES, "logs"); FIG = os.path.join(HERE, "figures")
KINDS = [("mlp_static", "MLP (no sequence)"), ("gru", "GRU"), ("bigru", "BiGRU"), ("abigru", "ABiGRU")]
SEEDS = (0, 1, 2)
# which log holds the run whose checkpoint is saved
LOG_OF = {(k, 0): "3_neural_seed0_retrain_with_saving.log" for k, _ in KINDS}
LOG_OF.update({(k, 1): "4_neural_seed1_and_abigru_seed2_retrain_with_saving.log" for k, _ in KINDS})
LOG_OF.update({(k, 2): "2_xgb_seeds_and_neural_seeds1-2_original.log" for k in ("mlp_static", "gru", "bigru")})
LOG_OF[("abigru", 2)] = "4_neural_seed1_and_abigru_seed2_retrain_with_saving.log"
EP = re.compile(r"^(\w+) s(\d) ep(\d+) loss ([\d.]+) val PR-AUC ([\d.]+) \((\d+)s\)")

def parse_log(fname):
    runs = {}
    for line in open(os.path.join(LOGS, fname), errors="replace"):
        m = EP.match(line.strip())
        if m:
            k, s, e, l, v, t = m.groups(); runs.setdefault((k, int(s)), []).append((int(e), float(l), float(v), int(t)))
    return runs

def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""): h.update(b)
    return h.hexdigest()

rows, hist, checks = [], {}, []
for k, label in KINDS:
    for s in SEEDS:
        info = json.load(open(f"{RES}/info_{k}_s{s}.json")); h = info["history"]
        ck = torch.load(f"{MOD}/{k}_s{s}.pt", map_location="cpu", weights_only=False)
        ck_ok = [round(x["val_pr_auc"], 6) for x in ck["history"]] == [round(x["val_pr_auc"], 6) for x in h]
        lg = parse_log(LOG_OF[(k, s)]).get((k, s), [])
        log_ok = len(lg) == len(h) and all(abs(a[1] - b["train_loss"]) < 5e-5 and abs(a[2] - b["val_pr_auc"]) < 5e-5 for a, b in zip(lg, h))
        best = int(np.argmax([x["val_pr_auc"] for x in h])) + 1
        secs = lg[-1][3] if lg else None
        rows.append(dict(model=label, kind=k, seed=s, epochs=len(h), best=best, best_val=max(x["val_pr_auc"] for x in h),
                         first_val=h[0]["val_pr_auc"], first_loss=h[0]["train_loss"], last_loss=h[-1]["train_loss"],
                         params=info["params"], secs=secs, stop="reached 14-epoch cap" if len(h) == 14 else "early stopping (3 epochs without gain)",
                         ck_ok=ck_ok, log_ok=log_ok, log=LOG_OF[(k, s)]))
        hist[(k, s)] = h
xgb_seed_iters = {}
for line in open(os.path.join(LOGS, "7_xgboost_seeds_rerun_with_saving.log"), errors="replace"):
    m = re.match(r"^(xgb_\w+) (\d) (\d+)$", line.strip())
    if m: xgb_seed_iters[(m.group(1), int(m.group(2)))] = int(m.group(3))
xgb_time = {}
for line in open(os.path.join(LOGS, "6_rules_xgboost_rerun_with_saving.log"), errors="replace"):
    m = re.match(r"^(xgb_\w+): best_iter=(\d+) time=(\d+)s$", line.strip())
    if m: xgb_time[m.group(1)] = (int(m.group(2)), int(m.group(3)))

# ---------------- report ----------------
tot_ep = sum(r["epochs"] for r in rows)
out = ["# Training report (evidence of training)\n",
       "Generated by `v2/training_report.py` from the saved training records, checkpoints and logs. Every number below can be traced to a file in this repository.\n",
       "## 1. What was trained\n",
       f"* **Neural models:** 4 architectures × 3 seeds = **12 training runs, {tot_ep} epochs in total**.",
       "* **XGBoost:** 4 variants (all features, no static features, no pool features, cold/new-function), with seeds 1 and 2 also for the first two = 8 fitted models.",
       "* **Data:** Huawei Cloud trace 2025, Region 5: 805,745 cold-start events, 31 days, 527 functions, cut into 5-minute buckets.",
       "* **Training rows:** 2,110,176 (431 functions × days 7–23). **Validation:** 372,384 (days 24–26). **Test:** 496,512 (days 27–30), of which 443,520 are scored in the main results.\n",
       "## 2. Neural training settings (identical for every run)\n",
       "| Setting | Value |", "|---|---|",
       "| Loss | binary cross-entropy on logits |", "| Optimizer | RMSprop, learning rate 0.001, alpha 0.9, eps 1e-8 |",
       "| Batch size | 2,048 |", "| One epoch | 700,000 training rows drawn at random from the 2,110,176 |",
       "| Max epochs | 14 |", "| Early stopping | stop after 3 epochs without validation PR-AUC gain; best epoch's weights restored |",
       "| Learning-rate schedule | halve when validation PR-AUC stalls for 1 epoch |", "| Gradient clipping | max norm 1.0 |",
       "| Inputs | 57 standardized features + a 24-step × 7-channel history window (MLP: features only) |",
       "| Device | Apple GPU (MPS) |", "| Code | `v2/run_deep.py`, `v2/nets.py` |\n",
       "## 3. Every neural training run\n",
       "| Model | Seed | Epochs run | Best (kept) epoch | Why it stopped | Train loss: epoch 1 → last | Val PR-AUC: epoch 1 → best | Parameters | Training time | Log ✓ | Checkpoint ✓ |",
       "|---|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    t = f"{r['secs'] // 60} min {r['secs'] % 60:02d} s" if r["secs"] is not None else "–"
    out.append(f"| {r['model']} | {r['seed']} | {r['epochs']} | {r['best']} | {r['stop']} | {r['first_loss']:.4f} → {r['last_loss']:.4f} | "
               f"{r['first_val']:.4f} → {r['best_val']:.4f} | {r['params']:,} | {t} | {'yes' if r['log_ok'] else 'NO'} | {'yes' if r['ck_ok'] else 'NO'} |")
out += [f"\n**Total: {tot_ep} epochs.** \"Log ✓\" = every epoch's loss and validation score in the training log matches the saved training record. "
        "\"Checkpoint ✓\" = the epoch history stored inside the saved model file matches it too. Training times are wall-clock seconds printed by the training script "
        "(several runs shared the machine with other jobs, so times vary).\n",
        "Epoch-by-epoch numbers for every run are in `v2/results/info_<model>_s<seed>.json`; the figure below plots them.\n",
        "![Training curves, all seeds](../figures/fig8_training_all_seeds.png)\n",
        "## 4. XGBoost training\n",
        "XGBoost has no epochs: it adds decision trees one at a time and stops when the validation score has not improved for 40 trees. "
        "Settings: max depth 8, learning rate 0.05, row and column sampling 0.8, min_child_weight 5, L2 1.0, up to 1,500 trees, evaluation metric PR-AUC.\n",
        "| Variant | Features | Seed | Trees kept | Fit time |", "|---|---|---|---|---|"]
NF = {"xgb_full": 57, "xgb_no_static": 46, "xgb_no_pool": 51, "xgb_cold_newfunc": 10}
for v in NF:
    it, tm = xgb_time.get(v, (json.load(open(f"{RES}/info_{v}.json"))["best_iter"], None))
    out.append(f"| {v} | {NF[v]} | 42 | {it} | {tm} s |" if tm else f"| {v} | {NF[v]} | 42 | {it} | – |")
    for s in (1, 2):
        if (v, s) in xgb_seed_iters: out.append(f"| {v} | {NF[v]} | {s} | {xgb_seed_iters[(v, s)]} | not timed separately |")
out += ["\n## 5. Saved model files and fingerprints\n",
        "SHA-256 fingerprints identify each file exactly: if a file is changed, its fingerprint changes. "
        "Check one with `shasum -a 256 v2/models/<file>` (macOS/Linux).\n",
        "| File | Size | SHA-256 |", "|---|---|---|"]
for p in sorted(glob.glob(f"{MOD}/*.pt")) + sorted(x for x in glob.glob(f"{MOD}/xgb_*_s*.json")):
    out.append(f"| `{os.path.basename(p)}` | {os.path.getsize(p) / 1e6:.2f} MB | `{sha(p)}` |")
out += ["\n## 6. Where the evidence is\n",
        "| Evidence | Location |", "|---|---|",
        "| Per-epoch records (loss, validation PR-AUC) | `v2/results/info_<model>_s<seed>.json` |",
        "| Console output printed during training | `v2/results/logs/` (local folder paths removed) |",
        "| Trained models | `v2/models/` (`.pt` neural, `.json` XGBoost) |",
        "| Training curves | `v2/figures/fig8_training_all_seeds.png` (all seeds), `fig6_training_curves.png` (seed 0) |",
        "| Training code | `v2/run_deep.py`, `v2/nets.py`, `v2/run_gbdt.py`, `v2/run_xgb_seeds.py` |",
        "| Test results produced by these models | `v2/results/benchmark.md`, `multiseed_summary.md`, `final_test_table.txt` |\n",
        "Which log holds which run: `1_` and `2_` are the original runs; `3_` and `4_` are the same runs repeated with model saving switched on "
        "(they reproduced the original predictions exactly); `5_`–`7_` are XGBoost; `8_` is the robustness study.\n",
        "## 7. How to demonstrate training live\n",
        "```bash",
        "COLDSTART_SMOKE=1 python3 v2/run_deep.py abigru 0   # 3 short epochs (~1 min); writes only to the system temp folder",
        "python3 v2/predict.py --model abigru_s0 --function 0 --day 28   # load the real trained model and predict",
        "```",
        "The smoke run prints one line per epoch (training loss, validation PR-AUC, elapsed time), the same format as the logs above."]
open(f"{RES}/training_report.md", "w").write("\n".join(out)); print("\n".join(out[:60]))

# ---------------- figure ----------------
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
os.makedirs(FIG, exist_ok=True)
fig, ax = plt.subplots(2, 4, figsize=(15, 6.4), sharex=True)
cols = {0: "#1f77b4", 1: "#ff7f0e", 2: "#2ca02c"}
for j, (k, label) in enumerate(KINDS):
    for s in SEEDS:
        h = hist[(k, s)]; e = np.arange(1, len(h) + 1)
        loss = [x["train_loss"] for x in h]; val = [x["val_pr_auc"] for x in h]; b = int(np.argmax(val))
        ax[0, j].plot(e, loss, "-o", ms=3, color=cols[s], label=f"seed {s}")
        ax[1, j].plot(e, val, "-o", ms=3, color=cols[s], label=f"seed {s} ({len(h)} epochs)")
        ax[1, j].scatter(e[b], val[b], s=90, marker="*", color=cols[s], edgecolor="black", linewidths=0.6, zorder=5)
    ax[0, j].set_title(label); ax[0, j].set_ylim(0.022, 0.048)
    ax[1, j].set_ylim(0.975, 0.987); ax[1, j].set_xlabel("epoch (700,000 rows each)")
    for a in ax[:, j]: a.grid(alpha=.3); a.set_xticks(range(1, 15))
    ax[1, j].legend(fontsize=7, loc="lower right")
ax[0, 0].set_ylabel("training loss (BCE)"); ax[1, 0].set_ylabel("validation PR-AUC")
fig.suptitle(f"Training of all 12 neural runs ({tot_ep} epochs). ★ = epoch kept (best validation PR-AUC); training stops after 3 epochs without gain or at 14. Y-axes zoomed.", fontsize=10)
fig.tight_layout(rect=(0, 0, 1, 0.95)); fig.savefig(f"{FIG}/fig8_training_all_seeds.png", dpi=150); print("figure saved")
if not all(r["log_ok"] and r["ck_ok"] for r in rows): sys.exit("CROSS-CHECK FAILED")
